export function registerLicenseRoutes(app: Express) {
  const canonicalValidationLimiter = rateLimit({
    windowMs: 60_000,
    limit: 20,
    standardHeaders: "draft-8",
    legacyHeaders: false,
    handler: (_req, res) => res.status(429).json({ success: false, status: "invalid", message: "Too many validation attempts. Please retry shortly." }),
  });
  const transportPingLimiter = rateLimit({
    windowMs: 60_000,
    limit: 20,
    standardHeaders: "draft-8",
    legacyHeaders: false,
    handler: (_req, res) => res.status(429).type("application/json").send('{"ok":false,"error":"rate_limited"}'),
  });

  // Key-free reachability diagnostic. This has no database, binding, or auth side effect.
  app.get("/v1/transport-ping", (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).type("application/json").send('{"ok":true,"service":"lua-license-panel"}');
  });

  app.post("/v1/transport-ping", (req, res) => {
    res.set("Cache-Control", "no-store");
    if (req.body?.test !== "ping") {
      return res.status(400).type("application/json").send('{"ok":false,"error":"invalid_ping"}');
    }
    return res.status(200).type("application/json").send('{"ok":true,"test":"ping"}');
  });

  // Correlated, key-free transport diagnostic. It records only a random caller-provided
  // probe ID and protocol lifecycle flags; it never stores IPs, keys, devices, tokens, or bodies.
  app.post("/ping", transportPingLimiter, (req, res) => {
    const requestId = req.get("X-Transport-Probe-Id");
    if (!isValidTransportProbeId(requestId)) {
      return res.status(400).type("application/json").send('{"ok":false,"error":"invalid_probe_id"}');
    }
    if (req.body?.test !== "ping" || Object.keys(req.body).length !== 1) {
      return res.status(400).type("application/json").send('{"ok":false,"error":"invalid_ping"}');
    }

    pruneTransportPingDiagnostics();
    const diagnostic: TransportPingDiagnostic = {
      requestId,
      requestReceived: true,
      httpMethod: "POST",
      requestBodyReceived: true,
      responseGenerated: true,
      responseSent: false,
      httpStatus: 200,
      receivedAt: new Date().toISOString(),
      responseFinishedAt: null,
    };
    transportPingDiagnostics.set(requestId, diagnostic);
    res.once("finish", () => {
      diagnostic.responseSent = true;
      diagnostic.responseFinishedAt = new Date().toISOString();
    });
    res.set("Cache-Control", "no-store");
    res.set("X-Transport-Probe-Id", requestId);
    return res.status(200).type("application/json").send('{"ok":true,"test":"ping"}');
  });

  app.get("/ping/diagnostic/:requestId", (req, res) => {
    const requestId = req.params.requestId;
    if (!isValidTransportProbeId(requestId)) {
      return res.status(400).type("application/json").send('{"ok":false,"error":"invalid_probe_id"}');
    }
    pruneTransportPingDiagnostics();
    const diagnostic = transportPingDiagnostics.get(requestId);
    if (!diagnostic) {
      return res.status(404).type("application/json").send('{"ok":false,"error":"diagnostic_not_found"}');
    }
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ ok: true, diagnostic });
  });

  app.post("/v1/validate", async (req, res) => {
    const key = typeof req.body?.key === "string" ? req.body.key : "";
    const deviceId = typeof req.body?.device_id === "string" ? req.body.device_id : "";
    if (!key || !deviceId) return res.status(403).json({ ok: false, error: "invalid_key" });
    const result = await validateLicense(key, deviceId);
    return res.status(result.ok ? 200 : 403).json(result);
  });

  app.get("/ping", (_req, res) => {
    res.status(200).type("text/plain").send("pong");
  });

  app.get("/health", (_req, res) => {
    res.status(200).type("text/plain").send("OK");
  });

  app.get("/api/announcement/active", async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ active: false });
  });

  app.post("/api/announcement/active", async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ active: false });
  });

  app.get("/api/maintenance/active", async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ active: false });
  });

  app.post("/api/maintenance/active", async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ active: false });
  });

  app.post("/api/telegram/ticket", canonicalValidationLimiter, async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ enabled: false, ticket: null });
  });

  app.post("/api/telegram/redeem", canonicalValidationLimiter, async (_req, res) => {
    res.set("Cache-Control", "no-store");
    return res.status(200).json({ enabled: false, channelUrl: null });
  });

  app.post("/api/license/validate", canonicalValidationLimiter, async (req, res) => {
    res.set("Cache-Control", "no-store");
    const key = typeof req.body?.key === "string" ? req.body.key.trim() : "";
    const deviceId = typeof req.body?.device_id === "string" ? req.body.device_id.trim() : "";
    if (!key || key.length > 128 || !deviceId || deviceId.length > 256) {
      return res.status(400).json({ success: false, status: "not_registered", message: "A valid key and device_id are required." });
    }
    try {
      return res.status(200).json(await validateCanonicalLicense(key, deviceId));
    } catch {
      return res.status(500).json({ success: false, status: "invalid", message: "Validation service is temporarily unavailable." });
    }
  });

}
