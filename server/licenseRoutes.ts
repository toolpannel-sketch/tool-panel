import type { Express, Request } from "express";
import rateLimit from "express-rate-limit";
import { getApiSharedSecret, validateCanonicalLicense, validateLicense } from "./license";

type TransportPingDiagnostic = {
  requestId: string;
  requestReceived: boolean;
  httpMethod: "POST";
  requestBodyReceived: boolean;
  responseGenerated: boolean;
  responseSent: boolean;
  httpStatus: number;
  receivedAt: string;
  responseFinishedAt: string | null;
};

const transportPingDiagnostics = new Map<string, TransportPingDiagnostic>();
const transportPingDiagnosticTtlMs = 30 * 60 * 1000;
const maxTransportPingDiagnostics = 100;

function isValidTransportProbeId(value: unknown): value is string {
  return typeof value === "string" && /^[A-Za-z0-9][A-Za-z0-9._-]{7,95}$/.test(value);
}

function pruneTransportPingDiagnostics(now = Date.now()) {
  for (const [requestId, diagnostic] of Array.from(transportPingDiagnostics.entries())) {
    if (now - Date.parse(diagnostic.receivedAt) > transportPingDiagnosticTtlMs) {
      transportPingDiagnostics.delete(requestId);
    }
  }
  while (transportPingDiagnostics.size >= maxTransportPingDiagnostics) {
    const oldestRequestId = transportPingDiagnostics.keys().next().value;
    if (!oldestRequestId) break;
    transportPingDiagnostics.delete(oldestRequestId);
  }
}

function originFor(req: Request) {
  const forwarded = req.headers["x-forwarded-proto"];
  const protocol = typeof forwarded === "string" ? forwarded.split(",")[0] : req.protocol;
  return `${protocol}://${req.get("host")}`;
}

